// Other apps live on the same github.io origin; only this app's caches are ours.
const PREFIX = 'mycalc-';

function cacheStrategy(urlString, selfOrigin) {
  let u;
  try { u = new URL(urlString); } catch (e) { return 'never'; }
  return u.origin === selfOrigin ? 'precache' : 'never';
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    // An update must not replace a complete offline copy with a partial one.
    const isUpdate = (await caches.keys()).some(n => n.startsWith(PREFIX) && n !== CACHE);
    const cache = await caches.open(CACHE);
    // Added one by one: on a first install a single 404 must not leave the app uninstalled.
    const results = await Promise.allSettled(ASSETS.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    const failed = results.map((r, i) => (r.status === 'rejected' ? ASSETS[i] : null)).filter(Boolean);
    if (failed.length) {
      console.warn('[sw] could not precache:', failed);
      if (isUpdate) {
        // Fail the install: the old worker and its cache stay; the browser retries later.
        await caches.delete(CACHE);
        throw new Error(`precache incomplete (${failed.length} files)`);
      }
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(n => n.startsWith(PREFIX) && n !== CACHE).map(n => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;
  if (cacheStrategy(request.url, self.location.origin) !== 'precache') return;
  const url = new URL(request.url);

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const root = new URL('./', self.location);
      const isRoot = url.pathname === root.pathname || url.pathname === `${root.pathname}index.html`;
      if (isRoot) {
        const cached = await caches.match('index.html');
        if (cached) return cached;
      }
      try {
        // Real sub-pages that are not precached (tests/) come from the network.
        return await fetch(request);
      } catch (e) {
        // Offline at a nested path: the shell's relative css/ and js/ would
        // resolve against the wrong depth, so redirect to the scope root; the
        // browser carries the #route across.
        if (!isRoot) return Response.redirect(root.pathname + url.search, 302);
        const cached = await caches.match('index.html');
        return cached || new Response('Offline', { status: 503 });
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request, { ignoreSearch: true });
    if (cached) return cached;
    try { return await fetch(request); } catch (e) { return new Response('', { status: 504 }); }
  })());
});
